"""The hanzi -> pinyin table the menu's search fields read (runtime/pinyin.c), from the Unicode Han Database.

    python tools/gen_pinyin_table.py Unihan_Readings.txt [runtime/pinyin_data.inc]
    python tools/gen_pinyin_table.py --download [runtime/pinyin_data.inc]

The table is not made from the game: the data is general Chinese, `kMandarin` of the Unicode Han Database
(https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip, third_party/unihan/LICENSE.txt), so every character the
game's text can hold has a reading. Tone marks are dropped and ü is written u (the search ignores both: see
runtime/pinyin.c), and characters above U+FFFF (Ext B and on: not text the game's message files use) are left out, so
a codepoint stays a uint16. One reading per character: the common one, which is what kMandarin gives; another reading
of a 多音字 is still found by the item's name or its actor.

The `.inc` is written into the tree: it is Unicode's data, not the game's, and a build without Python needs it.
"""
import io
import os
import sys
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UNIHAN_URL = 'https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip'
OUT = os.path.join(ROOT, 'runtime/pinyin_data.inc')

# A tone-marked vowel -> the plain letter, with ü as u (the search folds both sides the same way)
PLAIN = {
    'ā': 'a', 'á': 'a', 'ǎ': 'a', 'à': 'a',
    'ē': 'e', 'é': 'e', 'ě': 'e', 'è': 'e', 'ê': 'e',
    'ī': 'i', 'í': 'i', 'ǐ': 'i', 'ì': 'i',
    'ō': 'o', 'ó': 'o', 'ǒ': 'o', 'ò': 'o',
    'ū': 'u', 'ú': 'u', 'ǔ': 'u', 'ù': 'u',
    'ü': 'u', 'ǖ': 'u', 'ǘ': 'u', 'ǚ': 'u', 'ǜ': 'u',
    'ń': 'n', 'ň': 'n', 'ǹ': 'n', 'ḿ': 'm',
}
MAX_CP = 0xFFFF  # uint16 (see the module docstring)


def reading(text):
    """kMandarin's value as the search writes it: a-z only, tones and ü folded; None if nothing is left."""
    out = []
    for ch in text.split(' ')[0]:  # (a few entries list two readings: the first is the common one)
        if ch in PLAIN:
            out.append(PLAIN[ch])
        elif 'a' <= ch <= 'z':
            out.append(ch)
        elif 'A' <= ch <= 'Z':
            out.append(ch.lower())
        # (an apostrophe separates the syllables of a compound reading: dropped, the search has no boundaries)
    return ''.join(out) or None


def read_unihan(lines):
    """{codepoint: syllable} of Unihan_Readings.txt (any iterable of its lines)."""
    table = {}
    for line in lines:
        if line.startswith('#') or not line.strip():
            continue
        field = line.rstrip('\r\n').split('\t')
        if len(field) < 3 or field[1] != 'kMandarin':
            continue
        cp = int(field[0][2:], 16)
        if cp > MAX_CP:
            continue
        syl = reading(field[2])
        if syl:
            table[cp] = syl
    return table


def download():
    """Unihan_Readings.txt out of the Unicode zip (in memory: it is 8.8 MB extracted)."""
    with urllib.request.urlopen(UNIHAN_URL, timeout=180) as r:
        archive = zipfile.ZipFile(io.BytesIO(r.read()))
    return archive.read('Unihan_Readings.txt').decode('utf-8').splitlines()


def write_inc(table, out):
    cps = sorted(table)
    syllables = sorted({table[c] for c in cps})
    offset, at = {}, 0
    for s in syllables:  # the pool: the readings once each, NUL-terminated
        offset[s] = at
        at += len(s) + 1
    if at > 0xFFFF:
        raise SystemExit('the reading pool is %d bytes: too long for a uint16 offset' % at)
    lines = [
        '// Generated by tools/gen_pinyin_table.py from the Unicode Han Database (Unihan) - do not edit.',
        '// kMandarin of the characters up to U+FFFF, tone marks and ü folded to a-z (runtime/pinyin.c).',
        '// Unicode License v3: third_party/unihan/LICENSE.txt.',
        '',
        'static const char g_pinyin_readings[] =  // the readings once each, NUL-terminated: an offset is one reading',
    ]
    line = '   '
    for s in syllables:
        piece = s + '\\0'
        if len(line) + len(piece) + 3 > 100:
            lines.append(line)
            line = '   '
        line += ' "%s"' % piece
    lines.append(line + ';')
    lines += ['', 'static const uint16_t g_pinyin_offsets[] = {  // g_pinyin_readings offset, per character']
    line = '   '
    for c in cps:
        piece = '%d,' % offset[table[c]]
        if len(line) + len(piece) > 100:
            lines.append(line)
            line = '   '
        line += ' ' + piece
    lines.append(line.rstrip() + ' };')
    lines += ['', 'static const uint16_t g_pinyin_codepoints[] = {  // sorted, U+%04x..U+%04x' % (cps[0], cps[-1])]
    line = '   '
    for c in cps:
        piece = '0x%x,' % c
        if len(line) + len(piece) > 100:
            lines.append(line)
            line = '   '
        line += ' ' + piece
    lines.append(line.rstrip() + ' };')
    lines += ['', '#define PINYIN_CODEPOINTS %d' % len(cps), '']
    text = '\n'.join(lines)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return len(cps), len(syllables), at, len(text)


def main(argv):
    args = list(argv[1:])
    out = OUT
    if args and args[-1].endswith('.inc'):
        out = os.path.abspath(args.pop())
    if args == ['--download']:
        table = read_unihan(download())
    elif len(args) == 1:
        with open(args[0], encoding='utf-8') as f:
            table = read_unihan(f)
    else:
        raise SystemExit(__doc__)
    n, nread, pool, size = write_inc(table, out)
    print('%s: %d characters, %d readings, %d byte pool, %d bytes' % (out, n, nread, pool, size))


if __name__ == '__main__':
    main(sys.argv)
