#!/usr/bin/env python3
"""Generate the offline catalog; --source FILE imports an AmiiboAPI response.

Existing rows retain their order, keys and names to preserve settings and virtual
identities. New IDs are appended in sorted order. No network access at runtime.
Source: https://amiiboapi.org/docs/ and https://github.com/8bitDream/AmiiboAPI
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / 'data/amiibo.json'
HEADER = ROOT / 'runtime/amiibo_catalog.h'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, help='downloaded /api/amiibo/ JSON')
    parser.add_argument('--check', action='store_true', help='verify generated header is current')
    args = parser.parse_args()
    rows = json.loads(SNAPSHOT.read_text())
    if args.source:
        known = {r['id'] for r in rows}
        for a in sorted(json.loads(args.source.read_text())['amiibo'], key=lambda a: a['head'] + a['tail']):
            ident = (a['head'] + a['tail']).lower()
            if ident in known:
                continue
            group = 'The Legend of Zelda' if a['amiiboSeries'] == 'Legend Of Zelda' else a['amiiboSeries']
            rows.append(dict(key='id_' + ident, name=a['name'], id=ident, group=group,
                             game=a['gameSeries'], character=a['character'], kind=a['type']))
            known.add(ident)
    ids, keys = set(), set()
    groups = ['All series', 'Breath of the Wild', 'The Legend of Zelda', 'Super Smash Bros.']
    # Keep groups stable too: snapshot order is append-only.
    for row in rows:
        assert re.fullmatch('[0-9a-f]{16}', row['id']), row
        assert row['id'] not in ids and row['key'] not in keys, row
        ids.add(row['id']); keys.add(row['key'])
        if row['group'] not in groups:
            groups.append(row['group'])
    assert len(rows) < 0xffffff
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    lines = ['// Generated by tools/update_amiibo_catalog.py from data/amiibo.json. Do not edit.',
             '// Metadata source: https://amiiboapi.org/ (8bitDream/AmiiboAPI).', '#pragma once',
             f'#define AMIIBO_COUNT {len(rows)}', f'#define AMIIBO_SERIES_COUNT {len(groups)}',
             'static const char *const amiibo_series_names[AMIIBO_SERIES_COUNT] = {',
             *('    ' + quote(g) + ',' for g in groups), '};',
             'static const VirtualAmiibo virtual_amiibos[AMIIBO_COUNT] = {']
    for r in rows:
        raw = bytes.fromhex(r['id'])
        fields = [quote(r['key']), quote(r['name']), '{' + ', '.join(f'0x{x:02x}' for x in raw[:3]) + '}',
                  str(raw[3]), f'0x{int.from_bytes(raw[4:6], "big"):04x}', str(raw[6]), str(groups.index(r['group'])),
                  *(quote(r[k]) for k in ('id', 'game', 'character', 'kind'))]
        lines.append('    {' + ', '.join(fields) + '},')
    text = '\n'.join(lines + ['};', ''])
    if args.check:
        assert HEADER.read_text() == text, 'Run tools/update_amiibo_catalog.py'
    else:
        SNAPSHOT.write_text(json.dumps(rows, indent=2, ensure_ascii=False) + '\n')
        HEADER.write_text(text)
    print(f'{len(rows)} amiibo, {len(groups) - 1} series')

if __name__ == '__main__':
    main()
